import test from 'node:test';
import assert from 'node:assert/strict';
import { databaseFixture,loader } from './automation-test-fixture.mjs';
const {dashboardActivity}=loader()('db/dashboard-activity.ts');
test('daily record counts use Danish dates and Dinero receipts, not job counts',async t=>{
  const h=databaseFixture();t.after(()=>h.sql.close());
  h.record('order','before',{},'2026-09-08T21:59:59.999Z','booked');
  h.record('order','start',{},'2026-09-08T22:00:00.000Z');
  h.set('sales_transfer:start',{phase:'draft'});
  h.record('order','booked',{},'2026-09-09T10:00:00Z','booked');
  h.record('order','uncertain',{},'2026-09-09T10:00:00Z');
  h.set('sales_transfer:uncertain',{phase:'uncertain'});
  h.record('order','recovered',{},'2026-09-09T10:00:00Z','failed');
  h.set('sales_transfer:recovered',{phase:'booked'});
  h.record('order','tomorrow',{},'2026-09-09T22:00:00.000Z');
  h.record('payout','paid',{},'2026-09-09T08:00:00Z');
  h.set('payout_production:paid',{phase:'draft'});
  h.record('payout','failed',{},'2026-09-09T09:00:00Z','failed');
  h.record('payout','pending',{},'2026-09-09T09:00:00Z');
  const value=await dashboardActivity(h.db,new Date('2026-09-09T12:00:00Z'));
  assert.deepEqual(value.orders,{total:4,synced:3,failed:1});
  assert.deepEqual(value.payouts,{total:3,synced:1,failed:1});
});
test('last updates use completed imports and packaging marker, never a failed attempt',async t=>{
  const h=databaseFixture();t.after(()=>h.sql.close());
  const add=(id,key,status,date)=>h.sql.prepare("INSERT INTO job_runs(id,tenant,job_key,job_name,status,started_at,finished_at) VALUES(?,'sablen.dk',?,'Fixture',?,?,?)").run(id,key,status,date,date);
  add('1','shopify-orders','succeeded','2026-09-09T10:00:00Z');
  add('2','shopify-orders','failed','2026-09-09T11:00:00Z');
  add('3','shopify-refunds','skipped','2026-09-09T11:00:00Z');
  h.set('packaging:last-sync','2026-09-09T09:00:00Z');
  const value=await dashboardActivity(h.db,new Date('2026-09-09T12:00:00Z'));
  assert.equal(value.updated.sales,'2026-09-09T10:00:00Z');
  assert.equal(value.updated.refunds,null);assert.equal(value.updated.packaging,'2026-09-09T09:00:00Z');
  assert.deepEqual(value.orders,{total:0,synced:0,failed:0});
});
test('today spans the 23-hour Danish daylight-saving change',async t=>{
  const h=databaseFixture();t.after(()=>h.sql.close());
  h.record('order','in',{},'2026-03-28T23:00:00.000Z');
  h.record('order','out',{},'2026-03-29T22:00:00.000Z');
  assert.equal((await dashboardActivity(h.db,new Date('2026-03-29T12:00:00Z'))).orders.total,1);
});
